create table configurazione (
    chiave        varchar(100) primary key,
    valore        varchar(255) not null,
    data_modifica timestamp not null default (now() at time zone 'Europe/Rome')
);

create table tipologia_gioco (
    id_tipologia bigint generated by default as identity primary key,
    nome         varchar(100) not null
);

create table gioco (
    id_gioco     bigint generated by default as identity primary key,
    nome         varchar(150) not null,
    descrizione  text,
    fk_tipologia bigint not null references tipologia_gioco(id_tipologia) on delete restrict
);

create table piattaforma (
    id_piattaforma bigint generated by default as identity primary key,
    nome           varchar(100) not null
);

create table utente (
    id_utente     bigint generated by default as identity primary key,
    nickname      varchar(20)  not null unique,
    nome          varchar(100) not null,
    cognome       varchar(100) not null,
    email         varchar(255) not null unique,
    password_hash varchar(255) not null,
    ruolo         ruolo_utente not null default 'utente'
);

create table torneo (
    id_torneo                bigint generated by default as identity primary key,
    fk_organizzatore         bigint not null references utente(id_utente) on delete restrict,
    fk_gioco                 bigint not null references gioco(id_gioco)   on delete restrict,
    nome                     varchar(200) not null,
    max_posti                integer not null,
    long_desc                text,
    data_apertura_iscrizione timestamp not null,
    data_fine_iscrizione     timestamp not null,
    stato                    stato_torneo not null default 'bozza',
    giocatori_per_squadra    integer not null default 1,
    url_image                varchar(500),
    premio                   varchar(100),
    constraint ck_torneo_posti      check (max_posti >= 2),
    constraint ck_torneo_giocatori  check (giocatori_per_squadra >= 1),
    constraint ck_torneo_iscrizioni check (data_apertura_iscrizione < data_fine_iscrizione)
);

create table piattaforme_torneo (
    fk_torneo      bigint not null references torneo(id_torneo)           on delete cascade,
    fk_piattaforma bigint not null references piattaforma(id_piattaforma) on delete restrict,
    primary key (fk_torneo, fk_piattaforma)
);

create table squadra (
    id_squadra bigint generated by default as identity primary key,
    nome       varchar(100) not null
);

create table membro_squadra (
    fk_squadra     bigint not null references squadra(id_squadra) on delete cascade,
    fk_utente      bigint not null references utente(id_utente)   on delete cascade,
    ruolo_squadra  ruolo_squadra not null default 'giocatore',
    primary key (fk_squadra, fk_utente)
);

create unique index uq_un_capo_per_squadra
    on membro_squadra (fk_squadra) where ruolo_squadra = 'capo_squadra';

create table iscrizione (
    id_iscrizione   bigint generated by default as identity primary key,
    fk_torneo       bigint not null references torneo(id_torneo) on delete cascade,
    fk_squadra      bigint references squadra(id_squadra)        on delete cascade,
    fk_utente       bigint references utente(id_utente)          on delete cascade,
    data_iscrizione timestamp not null default (now() at time zone 'Europe/Rome'),
    stato           stato_iscrizione not null,
    constraint ck_iscrizione_partecipante
        check ((fk_squadra is not null)::int + (fk_utente is not null)::int = 1)
);

create unique index uq_iscrizione_squadra_attiva
    on iscrizione (fk_torneo, fk_squadra)
    where fk_squadra is not null and stato <> 'ritirata';

create unique index uq_iscrizione_utente_attiva
    on iscrizione (fk_torneo, fk_utente)
    where fk_utente is not null and stato <> 'ritirata';

create table partita (
    id_partita       bigint generated by default as identity primary key,
    fk_torneo        bigint not null references torneo(id_torneo) on delete cascade,
    round            integer not null,
    fk_iscrizione_a  bigint references iscrizione(id_iscrizione) on delete set null,
    fk_iscrizione_b  bigint references iscrizione(id_iscrizione) on delete set null,
    punteggio_a      integer,
    punteggio_b      integer,
    fk_vincitore     bigint references iscrizione(id_iscrizione) on delete set null,
    data_partita     timestamp,
    stato            stato_partita not null default 'programmata',
    constraint ck_partita_round     check (round >= 1),
    constraint ck_partita_punteggi  check ((punteggio_a is null or punteggio_a >= 0)
                                       and (punteggio_b is null or punteggio_b >= 0)),
    constraint ck_partita_diversi   check (fk_iscrizione_a is null or fk_iscrizione_b is null
                                       or fk_iscrizione_a <> fk_iscrizione_b),
    constraint ck_partita_vincitore check (fk_vincitore is null
                                       or fk_vincitore = fk_iscrizione_a
                                       or fk_vincitore = fk_iscrizione_b)
);


