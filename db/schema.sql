create function trg_limite_creatore() returns trigger
language plpgsql
set search_path = ''
as $$
begin
    if new.ruolo_squadra = 'capo_squadra'
       and (tg_op = 'INSERT' or old.ruolo_squadra <> 'capo_squadra')
       and (select count(*) from public.membro_squadra
            where fk_utente = new.fk_utente and ruolo_squadra = 'capo_squadra') >= 10 then
        raise exception 'Hai raggiunto il limite di 10 squadre';
    end if;
    return new;
end $$;

create trigger before_insert_capo
    before insert or update of ruolo_squadra on membro_squadra
    for each row execute function trg_limite_creatore();


create function trg_limite_membri() returns trigger
language plpgsql
set search_path = ''
as $$
begin
    if (select count(*) from public.membro_squadra where fk_squadra = new.fk_squadra) >= 28 then
        raise exception 'La squadra ha raggiunto il numero massimo di membri';
    end if;
    return new;
end $$;

create trigger before_insert_membro
    before insert on membro_squadra
    for each row execute function trg_limite_membri();


create function trg_limite_iscrizioni() returns trigger
language plpgsql
set search_path = ''
as $$
declare
    lim integer;
begin
    if new.fk_utente is null or new.stato = 'ritirata' then
        return new;
    end if;

    if tg_op = 'UPDATE' and old.stato <> 'ritirata' then
        return new;
    end if;

    select valore::integer into lim
    from public.configurazione
    where chiave = 'max_tornei_per_utente';

    if lim is not null
       and (select count(*)
            from public.iscrizione i
            join public.torneo t on t.id_torneo = i.fk_torneo
            where i.fk_utente = new.fk_utente
              and i.stato <> 'ritirata'
              and t.stato not in ('concluso', 'annullato')) >= lim then
        raise exception 'Puoi iscriverti a un massimo di % tornei', lim;
    end if;
    return new;
end $$;

create trigger before_insert_iscrizione
    before insert or update of stato on iscrizione
    for each row execute function trg_limite_iscrizioni();


